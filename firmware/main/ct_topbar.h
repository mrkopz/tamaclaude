//
// อยู่นอก root ของทุกหน้า ไม่ใช่ในหน้าใดหน้าหนึ่ง: เวลา โควตา และสถานะลิงก์เป็นสัญญากับ
// ผู้ใช้ว่าจะหาเจอที่เดิมเสมอ ไม่ว่ารอบหมุนจะพาไปหน้าไหน (เหตุผลเดียวกับ `ct_age`/`ct_mini`)
//
// ข้อมูลทั้งแถบมาจาก snapshot ของหน้ามาสคอต ซึ่งปิดไม่ได้ฝั่ง Mac — แถบจึงมีแหล่งข้อมูล
// เสมอ ไม่มีสภาพ "ไร้เวลาถาวร"
#pragma once

#include <stdbool.h>

#include "ct_model.h"
#include "layout.h"
#include "lvgl.h"

// สร้างแถบลงใต้ `scr` แล้วผูกกับ snapshot ที่จะอ่าน — ต้องเรียก *หลัง* สร้างทุกหน้าแล้ว
// LVGL เรียงชั้นตามลำดับสร้าง แถบที่สร้างทีหลังจึงอยู่บนสุดและไม่ถูกหน้าไหนบัง
void ct_topbar_init(lv_obj_t *scr, const ct_snapshot_t *mascot);

// หน้าที่แสดงอยู่เปลี่ยนไป — ชื่อบนแถบเปลี่ยนตาม และกติกา "ไม่พูดซ้ำ" ถูกคิดใหม่
void ct_topbar_set_page(ct_page_kind_t kind);

// snapshot ที่ผูกไว้เปลี่ยนแล้ว — วาดแถบใหม่ทั้งใบ
void ct_topbar_redraw(void);

// มี snapshot สดอยู่ไหม — จุดเป็นเทา ป้ายซ้ายพูดว่า "no link" นาฬิกาหรี่ โควตาหายทั้งชุด
void ct_topbar_set_connected(bool connected);

// ไอคอนลิงก์ขวาสุด — BLE ชนะ WiFi เสมอเพราะเป็นทางหลัก ทั้งคู่ false = ยังไม่มีใครคุยด้วย
// ไม่รับ `ip` แล้ว: ที่อยู่ของบอร์ดอยู่ในหน้าตั้งค่าบน Mac ที่เดียว ป้ายซ้ายเป็นชื่อหน้าล้วน
void ct_topbar_set_link(bool ble, bool wifi);
