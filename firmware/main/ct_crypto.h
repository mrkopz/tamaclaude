// ของราคา (BTC หกหลัก · DOGE ทศนิยมสี่ตำแหน่ง) และยังเป็นสิ่งที่ Mac ลดลงเองตอนบีบ
// เฟรมให้พอดี MTU บอร์ดที่จัดรูปเองจะไม่มีทางรู้ว่าเลขที่มันปัดทิ้งคือเลขที่ผู้ใช้ต้องเห็น
//
// เปอร์เซ็นต์มาเป็นจำนวนเต็มหน่วยสิบเท่า (-2.1% -> -21) — ไม่มีทศนิยมให้จัดรูป และ
// ความยาวคาดเดาได้ตอนวัดว่าเฟรมพอดีหรือยัง
#pragma once

#include <stdbool.h>

#include "layout.h"

// สัญลักษณ์ยาวกว่านี้ไม่มีในตลาดจริง (Mac ตัดที่ 5 ตัวอยู่แล้ว) ส่วนราคายาวสุดคือ
// เลขทศนิยมหกตำแหน่งของเหรียญที่ราคาต่ำมาก
#define CT_CRYPTO_SYM_LEN 8
#define CT_CRYPTO_PRICE_LEN 20

typedef struct {
    char sym[CT_CRYPTO_SYM_LEN];
    char price[CT_CRYPTO_PRICE_LEN];
    int change;  // เปอร์เซ็นต์คูณสิบ
} ct_crypto_row_t;

typedef struct {
    ct_crypto_row_t rows[CT_CRYPTO_ROWS];
    int count;
    // วินาทีนับจากตอนที่ Mac อ่านค่านี้มาได้จริง — บอร์ดนับต่อเองหลังจากนั้น
    int age;
} ct_crypto_t;

// แปลง JSON หนึ่งก้อนเป็นเฟรมคริปโต — คืน false เมื่อใช้ไม่ได้ (ของเดิมต้องไม่ถูกแตะ)
bool ct_crypto_parse(const char *json, int len, ct_crypto_t *out);

// เดินอายุข้อมูลไป `secs` วินาที — เรียกจากตัวโฮสต์ ไม่ใช่ตอนรับเฟรม
void ct_crypto_tick(ct_crypto_t *c, int secs);
