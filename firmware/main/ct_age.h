// บรรทัด data age ที่ทุกหน้าซึ่งไม่ใช่มาสคอตมีเหมือนกัน
//
// อยู่ที่นี่ที่เดียวเพราะมันเป็นสัญญากับผู้ใช้ ไม่ใช่รายละเอียดของหน้าใดหน้าหนึ่ง: ทุกหน้า
// บอกอายุข้อมูลด้วยถ้อยคำเดียวกัน ที่ตำแหน่งเดียวกัน และขึ้นคำว่า stale ด้วยเกณฑ์
// รูปเดียวกัน หน้าที่คัดลอกโค้ดนี้ไปไว้ในตัวเองจะดริฟต์ทีละคำจนผู้ใช้อ่านสองหน้าไม่เหมือนกัน
//
// ต้องตรงกับ tools/gen/age.py
#pragma once

#include <stdbool.h>
#include <stddef.h>

#include "lvgl.h"

// อายุข้อมูล -> ข้อความสั้นที่สุดที่ยังบอกได้ว่าควรเชื่อแค่ไหน
void ct_age_text(char *out, size_t cap, int secs);

// ช่วงเวลาเปล่าๆ ไม่มีคำว่า updated — ใช้ตอบ "หลุดลิงก์มานานเท่าไร" (หน้ามาสคอต)
//
// อยู่คู่กับ ct_age_text เพราะเป็นคำถามเดียวกัน ("ของชิ้นนี้เก่าแค่ไหน") คนละประโยค
// แยกไปเขียนใหม่ในหน้ามาสคอตเมื่อไร การปัดเศษนาทีของสองที่จะต่างกันเมื่อนั้น
void ct_age_gap_text(char *out, size_t cap, int secs);

// เก่าเกินกว่าจะบอกเป็นตัวเลขเฉยๆ แล้วหรือยัง (เกิน CT_PAGE_STALE_FACTOR เท่าของรอบดึง)
// รอบดึงเป็นของแต่ละหน้า ส่วนตัวคูณเป็นของทุกหน้า
bool ct_age_is_stale(int secs, int refresh_s);

// ป้ายบรรทัดอายุที่ตำแหน่งมาตรฐานก้นจอ
lv_obj_t *ct_age_label(lv_obj_t *parent);

// เขียนบรรทัดนั้นใหม่จากอายุปัจจุบัน — สีเปลี่ยนเองเมื่อข้อมูลเก่าเกินเกณฑ์
void ct_age_show(lv_obj_t *label, int secs, int refresh_s);

// อายุบวกเหตุผลที่ข้อมูลชุดนี้ *ควร* ค้าง เช่น "market closed" — ไม่มีคำว่า stale
//
// หน้าที่รู้ว่าข้อมูลของมันหยุดโดยชอบธรรมต้องไม่ตะโกนว่า stale: ราคาหุ้นตอนตีสองเก่า
// สิบชั่วโมงเป็นเรื่องปกติ ส่วนราคาคริปโตที่เก่าสิบชั่วโมงคือท่อพัง คำว่า stale จึงต้อง
// หมายถึงอย่างหลังเสมอ ไม่งั้นมันจะกลายเป็นคำที่ผู้ใช้เรียนรู้ที่จะมองข้าม
void ct_age_show_frozen(lv_obj_t *label, int secs, const char *why);
