// อยู่ที่นี่ที่เดียวด้วยเหตุผลเดียวกับ `ct_topbar`: คนที่ปัดจากหุ้นไปปฏิทินต้องเจอคำตอบของ
// "ข้อมูลเก่าแค่ไหน · session เป็นไง · จอกำลังจะทำอะไรต่อ" ที่เดิมเสมอ
//
// ไฟล์นี้เป็นเจ้าของ *แถบ* ส่วนของข้างในยังเป็นของเดิม: `ct_age` เขียนบรรทัดอายุ
// `ct_mini` วาดมาสคอต ที่รวมมาที่นี่คือการจัดวางกับสองอย่างที่เพิ่งมี — เส้นขอบบนที่
// ประกาศว่ามีฐานอยู่ และ pip ที่บอกตำแหน่งในรอบหมุน
#pragma once

#include <stdbool.h>

#include "lvgl.h"

// ตำแหน่งในรอบหมุน — `ct_pages` คำนวณแล้วผลักเข้ามา ไม่ใช่ไฟล์นี้ไปถามเอง
// (ทิศทางเดียวกับ `ct_mini_set_connected` และเป็นเหตุผลเดียวกัน: ct_pages เป็นตัวโฮสต์
// ฐานเป็นของที่มันแขวนไว้ ถ้าฐานย้อนไป include ตัวโฮสต์ก็จะวนกัน)
typedef struct {
    // ตำแหน่งของหน้าที่แสดงอยู่ในลิสต์ที่ *ปัดถึงได้จริง* — ไม่ใช่ดัชนีในแผน
    int index;
    // จำนวนหน้าที่ปัดถึงได้จริง (ผ่าน `in_rotation`) หน้าที่ยังไม่เคยได้เฟรมถูกข้ามตอนปัด
    // pip ที่นับมันด้วยคือคำสัญญาว่าปัดสองทีจะถึง ซึ่งไม่จริง
    int count;
    // เหลืออีกกี่ ms ก่อนจอเปลี่ยนหน้าเอง · < 0 = ไม่มีนาฬิกาเดินอยู่ (ปิดรอบหมุน)
    // ต่างจาก 0 ซึ่งคือกำลังจะพลิกเดี๋ยวนี้ — หลักเดียวกับ unknown != zero
    int left_ms;
    int total_ms;
} ct_footer_pos_t;

// `with_band` = หน้านี้ได้พื้น เส้น และแท่นใต้มาสคอตด้วยไหม
//
// หน้ามาสคอตส่ง false: ที่นั่นมาสคอตตัวจริงอยู่กลางจอแล้ว ไม่มีข้อมูลที่ดึงมาจึงไม่มีอายุ
// ให้บอก และพื้นดินกินถึงขอบล่าง แถบทึบจะตัดฉากทิ้ง · **แต่ pip ยังได้** เพราะหน้านั้น
// คือหน้าที่บอร์ดกระโดดกลับมาบ่อยที่สุด และ affordance ที่มี 4 ใน 5 หน้าสอนไม่สำเร็จ
void ct_footer_attach(lv_obj_t *parent, bool with_band);

// ไม่มี Mac = ไม่มีมาสคอต = ไม่มีแท่น (แท่นเปล่าอ่านว่า "ตัวหายไปไหน")
void ct_footer_set_connected(bool connected);

// เรียกได้ทุก tick — วาดใหม่เฉพาะตอนภาพที่ได้ *เปลี่ยนจริง* ไม่ใช่ตอนตัวเลขขยับ
// (ความกว้างที่เติมเป็นพิกเซลเต็ม รางกว้าง 14px ในรอบสิบวินาทีจึงขยับทุก ~700ms)
void ct_footer_set_pos(const ct_footer_pos_t *pos);
