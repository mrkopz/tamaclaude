// มาสคอตจิ๋วที่ทุกหน้าซึ่งไม่ใช่หน้ามาสคอตมีเหมือนกัน
//
// อยู่ที่นี่ที่เดียวด้วยเหตุผลเดียวกับ `ct_age`: มันเป็นสัญญากับผู้ใช้ ไม่ใช่รายละเอียดของ
// หน้าใดหน้าหนึ่ง คนที่ปัดจากหุ้นไปปฏิทินต้องเจอสถานะ session ที่มุมเดิม ขนาดเดิม ท่าเดิม
// หน้าที่คัดลอกโค้ดนี้ไปไว้ในตัวเองจะดริฟต์ทีละพิกเซลจนต้องค้นหาใหม่ทุกครั้งที่ปัด
//
// เฟสอนิเมชันอยู่ที่นี่ตัวเดียว ไม่ใช่ตัวละใบต่อหน้า — หน้าที่แสดงอยู่หน้าเดียวเท่านั้นที่
// ถูก tick การให้แต่ละหน้าถือเฟสของตัวเองแปลว่ามาสคอตกระตุกกลับไปเริ่มใหม่ทุกครั้งที่ปัด
//
// ต้องตรงกับ tools/gen/mini.py
#pragma once

#include "ct_model.h"
#include "lvgl.h"

// ผูกกับ snapshot ที่ตัวโฮสต์ถืออยู่ — เรียกครั้งเดียวก่อน attach ใบแรก
void ct_mini_init(const ct_snapshot_t *mascot);

// กล่องที่มาสคอตจิ๋วกิน — `ct_footer` ต้องรู้ว่าฝ่าเท้ากว้างแค่ไหนถึงจะวางแท่นให้ตรง
// คำนวณที่เดียวแล้วให้ทั้งตัววาดและตัวที่วางของใต้มันใช้ร่วมกัน แท่นที่คำนวณความกว้างเอง
// จะเลื่อนจากเท้าทันทีที่ `mini_unit_px` ขยับ — ตรงกับ `mini_box()` ใน tools/gen/mini.py
void ct_mini_box(int *x, int *y, int *w, int *h);

// ผืนวาดมาสคอตก้นจอของหน้านั้น — ตำแหน่งกับขนาดมาจาก `[footer] mini_*` ไม่ใช่จากหน้า
lv_obj_t *ct_mini_attach(lv_obj_t *parent);

// มี snapshot สดอยู่ไหม — ไม่มี Mac = ไม่มีมาสคอต ซึ่งต่างจากมาสคอตที่หลับ (= ไม่มี session)
void ct_mini_set_connected(bool connected);

// เดินเฟสอนิเมชันของหน้าที่แสดงอยู่ แล้ววาดใหม่
void ct_mini_tick(int elapsed_ms);
