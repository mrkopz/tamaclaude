// กติกาของทุกหน้า watchlist (คริปโต หุ้น) — สิ่งที่สองหน้าต้องทำเหมือนกันเป๊ะ
//
// อยู่ที่นี่ที่เดียวเพราะมันเป็นสัญญากับผู้ใช้ ไม่ใช่รายละเอียดของหน้าใดหน้าหนึ่ง: ลูกศรที่
// ชี้คนละแบบระหว่างสองหน้าคือจอที่ต้องอ่านสองครั้งเพื่อรู้เรื่องเดียวกัน · *พิกัด* ไม่ได้
// อยู่ที่นี่ มาโคร CT_CRYPTO_* กับ CT_STOCKS_* แยกกันคนละชุดโดยตั้งใจ (ดู layout.toml)
//
// สีอย่างเดียวไม่พอ: ตาบอดสีแดง-เขียวคือคนกลุ่มใหญ่ที่สุดที่ *ต้อง* แยกกำไรกับขาดทุนออก
// โดยไม่อ่านตัวเลข รูปทรงจึงเป็นตัวบอกหลัก ส่วนสีเป็นตัวช่วยที่สอง
//
// ต้องตรงกับ tools/gen/trend.py
#pragma once

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

#include "ct_rects.h"

// ระดับสูงสุดที่ nibble หนึ่งตัวเก็บได้ — ตรงกับที่ Mac quantize มาบนสาย
#define CT_TREND_SPARK_MAX 15

// เพดานจำนวนจุดที่ `ct_trend_spark` พับลงบัฟเฟอร์ของตัวเองได้ · **ไม่ใช่** CT_CRYPTO_SPARK_COLS
// ไฟล์นี้เป็นกติกาที่ทุกหน้าใช้ร่วมกัน มันจึงต้องไม่รู้จักมาโครของหน้าใดหน้าหนึ่ง (เหตุผล
// เดียวกับที่ layout.toml ไม่ให้หน้าหุ้นอ่าน CT_CRYPTO_*) หน้าที่ใช้เป็นคนยืนยันด้วย
// _Static_assert ว่าค่าของตัวเองไม่เกินเพดานนี้
#define CT_TREND_SPARK_COLS_MAX 16

// สีของแถวหนึ่ง — ทั้งลูกศรและตัวเลขเปอร์เซ็นต์อ่านจากที่เดียวกัน ไม่งั้นสองอย่างที่อยู่
// ติดกันจะเถียงกันเองได้เมื่อมีใครแก้ทางใดทางหนึ่ง
uint16_t ct_trend_tone(int change, bool connected);

// พื้นการ์ดของแถวแรก · `live` = ตัวเลขชุดนี้ยังเดินอยู่จริงไหม ซึ่งไม่เท่ากับ `connected`:
// หุ้นตอนตลาดปิดยังต่อลิงก์อยู่ แต่ราคาหยุดเดินโดยชอบธรรม ทั้งสองกรณีได้พื้นกลาง เพราะ
// การ์ดที่ยังเขียวอยู่ตอนตัวเลขไม่ขยับคือการโกหก
uint16_t ct_trend_card_fill(int change, bool live);

// ขอบการ์ด — ไม่ใช่ `ct_trend_tone` แม้จะตอบคำถามเดียวกัน: ขอบมีหน้าที่ประกาศว่า
// *มีการ์ดอยู่* ส่วนหน้าที่ประกาศ *ทิศทาง* เป็นของลูกศรกับแท่งซึ่งเต็มแรงอยู่แล้ว
// กรอบ 303px ด้วยสีเต็มแรงอ่านเป็นกล่อง error (เหตุผลเต็มอยู่ที่ card_edge_up ใน layout.toml)
uint16_t ct_trend_card_edge(int change, bool connected);

// ลูกศรขึ้น/ลงในตาราง 4x4 unit — ผู้เรียกเป็นคนกำหนดขนาดพิกเซลต่อ unit
void ct_trend_arrow(ct_rects_t *out, int change, bool connected);

// ย่อจำนวนจุดลงเหลือ `cols` โดย **เก็บปลายทั้งสองไว้เสมอ** — เฉลี่ยเป็นคู่ๆ จะทำให้จุด
// สุดท้ายไม่ใช่ราคาปิดอีกต่อไป แล้วแท่งสุดท้ายก็เลิกตรงกับเปอร์เซ็นต์ที่พิมพ์อยู่ข้างมัน
// คืนจำนวนจุดที่เขียนลง `out` (ซึ่งต้องรับได้อย่างน้อย `cols` ตัว)
int ct_trend_fold(const uint8_t *levels, int n, uint8_t *out, int cols);

// รูปราคา 24 ชั่วโมงเป็นแท่ง ในพิกัด *พิกเซล* (px = 1) ไม่ใช่ unit เหมือนลูกศร
//
// **เส้นฐานคือจุดแรก** ซึ่งคือราคาเปิดของ 24 ชั่วโมง แท่งเหนือเส้น = แพงกว่าตอนเปิด
// จมใต้เส้น = ถูกกว่า ทิศทางจึงเป็น *ตำแหน่ง* ที่คนตาบอดสีอ่านได้เท่ากัน และแท่งสุดท้าย
// เทียบเส้นฐาน = เปอร์เซ็นต์ที่พิมพ์อยู่ โดยโครงสร้าง ไม่ใช่โดยบังเอิญ
// `n == 0` (ไม่มีประวัติ) = เส้นฐานเปล่ากลางกล่อง ไม่ใช่กล่องว่าง
void ct_trend_spark(ct_rects_t *out, const uint8_t *levels, int n, int w, int h, int cols,
                    int pitch, int bar, bool connected);

// หั่นราคาเป็นก้อนฟอนต์ใหญ่ (จำนวนเต็ม) กับก้อนฟอนต์เล็ก (จุด + ทศนิยม)
// `head` ว่าง = ทั้งก้อนต้องใช้ฟอนต์เล็ก ซึ่งเกิดเมื่อจำนวนเต็มยาวเกิน `int_digits_max`
// หรือราคาไม่มีจุดเลย (ไม่ควรเกิดหลัง Mac ตรึงทศนิยมไว้ แต่บอร์ดไม่ได้เชื่อ Mac)
void ct_trend_split_price(const char *price, int int_digits_max, char *head, size_t head_cap,
                          char *tail, size_t tail_cap);

// เปอร์เซ็นต์คูณสิบ -> ข้อความที่มีเครื่องหมายเสมอ ("+1.1%")
void ct_trend_pct_text(char *out, size_t cap, int change);
