// RGB565 (สีที่แผงจอกินจริง และเป็นสิ่งที่ layout.toml เก็บ) -> สีของ LVGL
//
// อยู่ที่นี่เพราะมีคนใช้มากกว่าหนึ่งโมดูลแล้ว การแปลงต้องเหมือนกันเป๊ะทุกจุด ไม่งั้นพื้นหลัง
// ของจอกับพื้นหลังที่หน้าวาดเองจะเป็นคนละสีที่ต่างกันหนึ่งขั้น
#pragma once

#include <stdint.h>

#include "lvgl.h"

// ขยายกลับเป็น 8 บิตต่อช่องแบบเดียวกับ quantize565 ฝั่ง Python
static inline lv_color_t ct_color(uint16_t c)
{
    uint8_t r5 = (c >> 11) & 0x1F, g6 = (c >> 5) & 0x3F, b5 = c & 0x1F;
    return lv_color_make((r5 * 255 + 15) / 31, (g6 * 255 + 31) / 63, (b5 * 255 + 15) / 31);
}
